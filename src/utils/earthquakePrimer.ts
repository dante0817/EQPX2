/**
 * Deterministically builds an Earthquake Primer draft from the currently active EQPEvent
 * including the Stage 2 Epicenter & Geographic Context figure snapshot.
 * Never mutates event state and never auto-publishes.
 */
export function generateInitialEarthquakePrimer(
  event: EQPEvent,
  options: GeneratePrimerOptions = {}
): PrimerDocument {
  const nowIso = new Date().toISOString();
  const trigger: PrimerGenerationTrigger = options.trigger ?? 'manual';
  const rules = options.rules ?? DEFAULT_PRIMER_ELIGIBILITY_RULES;

  const extracted = extractVerifiedPrimerParameters(event, options);
  const eligibilitySnapshot = evaluatePrimerEligibility(event, rules, options);

  const magHeader =
    extracted.magnitudeValue !== null && extracted.magnitudeScale
      ? `${extracted.magnitudeScale} ${extracted.magnitudeValue.toFixed(1)} `
      : '';
  const placeHeader = extracted.primaryLocationLabel
    ? extracted.primaryLocationLabel
    : 'Location Pending';
  const dateHeader = formatIsoDateHuman(extracted.originDatePst);

  const title = `PRIMER ON THE ${dateHeader.toUpperCase()} ${magHeader}EARTHQUAKE (${placeHeader})`;
  const subtitle = `Draft Technical Summary — Event ${extracted.eventId} (Bulletin No. ${extracted.bulletinNo})`;

  const sections: PrimerSection[] = [
    buildSectionOverview(extracted),
    buildSectionLocation(extracted),
    buildSectionAftershocks(extracted),
    buildSectionIntensity(extracted),
    buildSectionTectonicSetting(extracted),
    buildSectionHazards(extracted),
    buildSectionRecommendations(extracted),
  ];

  const epicenterFigure =
    options.includeFigure !== false
      ? generatePrimerEpicenterFigure(event, {
          ...(options.figureOptions ?? {}),
          primaryLocationLabel: options.primaryLocationLabel,
          faultGeneratorLabel: options.faultGeneratorLabel,
          isPlotResultStale: options.isSolutionStale,
        })
      : undefined;

  return {
    id: `primer_${extracted.eventId}_${Date.now()}`,
    schemaVersion: '1.0',
    eventId: extracted.eventId,
    bulletinNo: extracted.bulletinNo,
    status: 'draft',
    title,
    subtitle,
    generatedAt: nowIso,
    updatedAt: nowIso,
    savedAt: null,
    generationTrigger: trigger,
    eligibilitySnapshot,
    extracted,
    sections,
    extensions: {
      ...(epicenterFigure ? { epicenterFigure } : {}),
      reviewVersioning: {
        revisionNumber: 1,
      },
    },
  };
}


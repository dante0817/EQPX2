/**
 * Updates Stage 3 Sequence & Historical Seismicity integration on an existing primer draft.
 * Non-destructive by default: preserves manually edited Section 3 ("aftershocks") content unless
 * `forceOverwriteEdited` is explicitly true, while always updating `autoGeneratedBaseline`.
 */
export function updatePrimerSequenceHistoricalAnalysis(
  primer: PrimerDocument,
  pkg: PrimerStage3Package,
  options: UpdatePrimerStage3Options = {}
): PrimerDocument {
  const nextBaseline = formatStage3AftershockSectionText(
    pkg,
    primer.extracted.expectingAftershocks
  );

  const stage3Flags: string[] = [];
  if (pkg.statistics.membershipBasis === 'candidate-spatiotemporal-window') {
    stage3Flags.push(
      'Aftershock counts reflect spatiotemporal catalog candidates; formal sequence membership requires scientific review'
    );
  } else if (pkg.statistics.membershipBasis === 'unavailable') {
    stage3Flags.push(
      'Catalog records or reference epicenter coordinates unavailable for automated aftershock statistics'
    );
  }
  if (pkg.statistics.hasMixedMagnitudeScales) {
    stage3Flags.push(
      'Catalog contains mixed magnitude scales reported separately without homogenization'
    );
  }
  if (pkg.statistics.uncertainDuplicateFlaggedCount > 0) {
    stage3Flags.push(
      `${pkg.statistics.uncertainDuplicateFlaggedCount} uncertain cross-source duplicate match(es) flagged`
    );
  }
  if (pkg.statistics.incompleteMissingDepthCount > 0) {
    stage3Flags.push(
      `${pkg.statistics.incompleteMissingDepthCount} post-event record(s) missing focal depth`
    );
  }

  const nextSections = primer.sections.map((sec) => {
    if (sec.id !== 'aftershocks') return sec;
    const shouldReplaceContent =
      Boolean(options.forceOverwriteEdited) ||
      (options.syncAftershocksSection !== false && !sec.isEdited);

    if (!shouldReplaceContent) {
      return {
        ...sec,
        autoGeneratedBaseline: nextBaseline,
      };
    }

    return {
      ...sec,
      content: nextBaseline,
      autoGeneratedBaseline: nextBaseline,
      isEdited: options.forceOverwriteEdited ? false : sec.isEdited,
      reviewStatus: pkg.provenance.reviewStatus,
      reviewFlags:
        stage3Flags.length > 0
          ? stage3Flags
          : ['Automated Stage 3 sequence summary ready for duty seismologist review'],
    };
  });

  return {
    ...primer,
    updatedAt: new Date().toISOString(),
    sections: nextSections,
    extensions: {
      ...(primer.extensions ?? {}),
      sequenceHistoricalAnalysis: pkg,
      aftershockAnalysis: {
        catalogCount: pkg.statistics.eligiblePostEventCount,
        maxAftershockMag: pkg.statistics.maxAftershock?.magnitude ?? null,
        windowHours: pkg.config.filters.postDays * 24,
      },
      historicalContext: {
        nearbySignificantCount: pkg.historical.totalMatchingCount,
        notes: pkg.historical.associationDisclaimer,
      },
    },
  };
}

export interface UpdatePrimerStage4Options {
  syncSections?: boolean;
  forceOverwriteEdited?: boolean;
  targetSectionIds?: PrimerSectionKey[];
}

/**
 * Attaches Stage 4 structured narratives, subsections, and source provenance ledger to a PrimerDocument.
 * Non-destructive by default: preserves manually edited `section.content` unless `forceOverwriteEdited` is true,
 * while always updating `autoGeneratedBaseline`, `contentState`, `missingIndicators`, and `subsections`.
 */
export function updatePrimerStage4Narratives(
  primer: PrimerDocument,
  pkg: PrimerStage4NarrativePackage,
  options: UpdatePrimerStage4Options = {}
): PrimerDocument {
  const nextSections = primer.sections.map((sec) => {
    const block = pkg.sectionNarratives[sec.id];
    if (!block) return sec;

    const targeted =
      !options.targetSectionIds || options.targetSectionIds.includes(sec.id);
    const shouldReplaceContent =
      targeted &&
      (Boolean(options.forceOverwriteEdited) ||
        (options.syncSections !== false && !sec.isEdited));

    if (!shouldReplaceContent) {
      return {
        ...sec,
        autoGeneratedBaseline: block.renderedText,
        contentState: block.contentState,
        missingIndicators: block.missingIndicators,
        subsections: block.subsections,
      };
    }

    return {
      ...sec,
      content: block.renderedText,
      autoGeneratedBaseline: block.renderedText,
      isEdited: options.forceOverwriteEdited ? false : sec.isEdited,
      reviewStatus: block.reviewStatus,
      reviewFlags:
        block.missingIndicators.length > 0
          ? block.missingIndicators
          : [`Stage 4 narrative compiled (${pkg.templateVersion})`],
      contentState: block.contentState,
      missingIndicators: block.missingIndicators,
      subsections: block.subsections,
    };
  });

  return {
    ...primer,
    updatedAt: new Date().toISOString(),
    sections: nextSections,
    extensions: {
      ...(primer.extensions ?? {}),
      scientificNarrativePackage: pkg,
    },
  };
}


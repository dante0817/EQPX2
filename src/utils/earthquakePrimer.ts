function buildSectionIntensity(p: PrimerExtractedParameters): PrimerSection {
  const reviewFlags: string[] = [];
  const lines: string[] = [];

  if (p.verifiedIntensityText.trim()) {
    lines.push(
      'Reported and instrumental intensities (PHIVOLCS Earthquake Intensity Scale, PEIS) verified in the active event record:'
    );
    lines.push('');
    lines.push(p.verifiedIntensityText);
  } else {
    reviewFlags.push('No verified felt or instrumental PEIS intensities recorded');
    lines.push(
      '[REQUIRES INFORMATION: No verified PHIVOLCS Earthquake Intensity Scale (PEIS) felt or instrumental intensity reports are currently recorded for this event.]'
    );
  }

  if (p.unverifiedIntensityCount > 0) {
    reviewFlags.push(
      `${p.unverifiedIntensityCount} intensity report(s) remain in draft, conflicting, or unresolved status`
    );
    lines.push('');
    lines.push(
      `[REQUIRES SCIENTIFIC REVIEW: ${p.unverifiedIntensityCount} additional intensity report(s) remain in draft, conflicting, or unresolved status and were excluded from the verified list above pending validation.]`
    );
  }

  const reviewStatus: PrimerSectionReviewStatus =
    !p.verifiedIntensityText.trim()
      ? 'requires-info'
      : p.unverifiedIntensityCount > 0
        ? 'requires-scientific-review'
        : 'ready-for-review';

  const content = lines.join('\n');
  return {
    id: 'intensity',
    order: 4,
    title: '4. Reported & Instrumental Intensities (PEIS)',
    content,
    reviewStatus,
    reviewFlags,
    isEdited: false,
    autoGeneratedBaseline: content,
  };
}

function buildSectionTectonicSetting(p: PrimerExtractedParameters): PrimerSection {
  const reviewFlags: string[] = [
    'Causative fault identification, focal mechanism, and regional tectonic narrative require geologist/seismologist scientific review',
  ];
  const lines: string[] = [];

  if (p.originType) {
    lines.push(`Recorded Earthquake Origin Classification: ${p.originType}`);
  } else {
    reviewFlags.push('Earthquake origin type not specified');
    lines.push('Recorded Earthquake Origin Classification: [REQUIRES INFORMATION]');
  }

  if (p.nearestFaultLabel) {
    lines.push(`Nearest Mapped Tectonic Generator (Proximity Reference): ${p.nearestFaultLabel}`);
  } else {
    reviewFlags.push('Nearest mapped fault/trench generator reference unavailable');
    lines.push(
      'Nearest Mapped Tectonic Generator: [REQUIRES INFORMATION — run Nearest Places / GIS fault distance check]'
    );
  }

  lines.push(
    '',
    '[REQUIRES SCIENTIFIC REVIEW: Proximity to a mapped active fault or trench does not automatically confirm the causative source structure. Geologic interpretation, focal mechanism / nodal plane correlation, and historical seismicity context require specialist review (automated historical/tectonic enrichment planned for Stage 2).]'
  );

  const reviewStatus: PrimerSectionReviewStatus =
    !p.nearestFaultLabel || !p.originType
      ? 'requires-info'
      : 'requires-scientific-review';

  const content = lines.join('\n');
  return {
    id: 'tectonic_setting',
    order: 5,
    title: '5. Tectonic Setting & Possible Earthquake Source',
    content,
    reviewStatus,
    reviewFlags,
    isEdited: false,
    autoGeneratedBaseline: content,
  };
}


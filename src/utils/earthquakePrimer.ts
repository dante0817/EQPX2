    '[REQUIRES SCIENTIFIC REVIEW: Comprehensive earthquake hazard assessments—including near-source ground shaking intensity distribution, potential for liquefaction in saturated alluvial deposits, earthquake-induced landslides on steep slopes, surface fault rupture, and detailed sea-level/tsunami modeling—must be reviewed and authored by PHIVOLCS hazard specialists prior to primer release.]',

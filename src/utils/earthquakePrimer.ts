function peisRank(peis: PeisRoman): number {
  return PEIS_LEVELS.indexOf(peis) + 1;
}

function formatIsoDateHuman(isoDate: string): string {
  const parts = isoDate.split('-');
  if (parts.length !== 3) return isoDate || 'Unavailable';
  const [yyyy, mm, dd] = parts;
  const idx = Math.max(0, Math.min(11, (Number(mm) || 1) - 1));
  return `${dd.padStart(2, '0')} ${MONTHS_SHORT[idx]} ${yyyy}`;
}

function formatUtcTimeShort(timeStr: string): string {
  const trimmed = timeStr.trim();
  if (!trimmed) return 'Unavailable';
  const parts = trimmed.split(':');
  if (parts.length < 2) return trimmed;
  const hh = parts[0].padStart(2, '0');
  const mm = parts[1].padStart(2, '0');
  const ss = parts[2] ? parts[2].split('.')[0].padStart(2, '0') : '00';
  return `${hh}:${mm}:${ss} UTC`;
}

function formatPstTimeShort(timeStr: string): string {
  const trimmed = timeStr.trim();
  if (!trimmed) return 'Unavailable';
  const parts = trimmed.split(':');
  if (parts.length < 2) return trimmed;
  const h24 = Math.max(0, Math.min(23, Number(parts[0]) || 0));
  const mm = String(Math.max(0, Math.min(59, Number(parts[1]) || 0))).padStart(2, '0');
  const ss = parts[2]
    ? String(Math.max(0, Math.min(59, Math.round(Number(parts[2]) || 0)))).padStart(2, '0')
    : '00';
  const amPm = h24 >= 12 ? 'PM' : 'AM';
  const h12 = String(h24 % 12 || 12).padStart(2, '0');
  return `${h12}:${mm}:${ss} ${amPm} PST`;
}

function escapeHtml(raw: string): string {
  return raw
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}


/**
 * Extracts only verified and genuinely available fields from the active EQPEvent.
 * Never mutates the input event and never fabricates missing measurements.
 */
export function extractVerifiedPrimerParameters(
  event: EQPEvent,
  options: ExtractPrimerParamsOptions = {}
): PrimerExtractedParameters {
  const unlocated = isEventUnlocated(event);
  const rawActiveMag =
    event.preferredScale === 'Ms'
      ? event.ms
      : event.preferredScale === 'Mb'
        ? event.mb
        : event.md;
  const hasMag = Number.isFinite(rawActiveMag) && rawActiveMag > 0;

  const selectedCity = event.cities.find((c) => c.id === event.selectedCityId) ?? null;
  const selectedTown = event.towns.find((t) => t.id === event.selectedTownId) ?? null;
  const fallbackHeadline =
    event.primaryHeadline === 'town'
      ? selectedTown?.label ?? selectedCity?.label ?? null
      : selectedCity?.label ?? selectedTown?.label ?? null;

  const resolvedHeadline =
    options.primaryLocationLabel && options.primaryLocationLabel !== 'Location pending'
      ? options.primaryLocationLabel
      : fallbackHeadline;

  const selectedGen =
    event.generators.find((g) => g.id === event.selectedGeneratorId) ?? null;
  const nearestFaultLabel = options.faultGeneratorLabel ?? selectedGen?.label ?? null;

  const intensityAnalysis = analyzeIntensityEntries(event.intensities);
  const groupedIntensity = formatGroupedBulletinIntensityBlock(event.intensities);

  const verifiedAll = [
    ...intensityAnalysis.eligibleFelt,
    ...intensityAnalysis.eligibleInstrumental,
  ];
  let maxVerifiedPeis: PeisRoman | null = null;
  for (const entry of verifiedAll) {
    if (!maxVerifiedPeis || peisRank(entry.peis) > peisRank(maxVerifiedPeis)) {
      maxVerifiedPeis = entry.peis;
    }
  }

  const unverifiedIntensityCount =
    intensityAnalysis.counts.draft +
    intensityAnalysis.counts.conflicting +
    intensityAnalysis.counts.unresolved;

  const activeStationCount = event.picks.filter(
    (p) => !p.pExcluded || (p.sTime.trim() !== '' && !p.sExcluded)
  ).length;

  const unavailableOrUnverifiedFields: string[] = [];
  if (unlocated) {
    unavailableOrUnverifiedFields.push('Hypocenter coordinates and focal depth (pending location)');
  }
  if (!hasMag) {
    unavailableOrUnverifiedFields.push(`Magnitude (${event.preferredScale} not yet computed)`);
  }
  if (options.isSolutionStale) {
    unavailableOrUnverifiedFields.push(
      'Location solution is stale relative to modified station picks'
    );
  }
  if (!resolvedHeadline || unlocated) {
    unavailableOrUnverifiedFields.push('Primary nearest city/municipality reference');
  }
  if (!nearestFaultLabel) {
    unavailableOrUnverifiedFields.push('Nearest active fault / trench generator reference');
  }
  if (intensityAnalysis.eligibleFelt.length === 0) {
    unavailableOrUnverifiedFields.push('Verified felt intensity (PEIS) observations');
  }
  if (unverifiedIntensityCount > 0) {
    unavailableOrUnverifiedFields.push(
      `${unverifiedIntensityCount} intensity report(s) pending verification or conflict resolution`
    );
  }

  return {
    eventId: event.id,
    filename: event.filename,
    bulletinNo: Math.max(1, Math.trunc(event.bulletinNo || 1)),
    originDateUtc: event.originDateGmt?.trim() || 'Unavailable',
    originTimeUtc: event.originTimeGmt?.trim() || 'Unavailable',
    originDatePst: event.originDateLst?.trim() || 'Unavailable',
    originTimePst: event.originTimeLst?.trim() || 'Unavailable',
    isLocated: !unlocated,
    lat: !unlocated && Number.isFinite(event.lat) ? event.lat : null,
    lon: !unlocated && Number.isFinite(event.lon) ? event.lon : null,
    depthKm: !unlocated && Number.isFinite(event.depthKm) ? event.depthKm : null,
    depthFixed: Boolean(event.locationMetadata?.depthFixed),
    depthFixReason: event.locationMetadata?.depthFixReason ?? null,
    magnitudeScale: hasMag ? event.preferredScale : null,
    magnitudeValue: hasMag ? rawActiveMag : null,
    allMagnitudes: {
      ms: event.ms > 0 ? event.ms : null,
      mb: event.mb > 0 ? event.mb : null,
      md: event.md > 0 ? event.md : null,
    },
    errKm: !unlocated && Number.isFinite(event.errKm) && event.errKm > 0 ? event.errKm : null,
    rmsSec: !unlocated && Number.isFinite(event.rmsSec) ? event.rmsSec : null,
    stationCount: event.picks.length,
    activeStationCount,
    primaryLocationLabel: !unlocated ? resolvedHeadline : null,
    centralOfficeBearing: !unlocated ? event.centralOfficeBearing?.trim() || null : null,
    nearestFaultLabel: !unlocated ? nearestFaultLabel : null,
    originType: event.originType ?? null,
    tsunamiStatus: event.tsunamiStatus ?? 'None',
    expectingDamage: Boolean(event.expectingDamage),
    expectingAftershocks: Boolean(event.expectingAftershocks),
    verifiedFeltCount: intensityAnalysis.eligibleFelt.length,
    verifiedInstrumentalCount: intensityAnalysis.eligibleInstrumental.length,
    unverifiedIntensityCount,
    maxVerifiedPeis,
    verifiedIntensityText: groupedIntensity.text,
    issuedBy: event.issuedBy?.trim() || null,
    locationModelName: event.locationMetadata?.modelName ?? null,
    locationValidationStatus: event.locationMetadata?.validationStatus ?? null,
    isSolutionStale: Boolean(options.isSolutionStale),
    unavailableOrUnverifiedFields,
  };
}

/**
 * Evaluates configurable automatic draft eligibility rules against the active event.
 * Note: Manual primer generation is always allowed regardless of this evaluation.
 */
export function evaluatePrimerEligibility(
  event: EQPEvent,
  rules: PrimerAutoEligibilityRule,
  options: ExtractPrimerParamsOptions = {}
): PrimerEligibilityEvaluation {
  const params = extractVerifiedPrimerParameters(event, options);
  const matchedCriteria: string[] = [];
  const unmetCriteria: string[] = [];

  if (!rules.enabled) {
    unmetCriteria.push('Automatic draft generation rule is disabled');
    return {
      eligible: false,
      activeMagnitude: params.magnitudeValue,
      maxVerifiedPeis: params.maxVerifiedPeis,
      matchedCriteria,
      unmetCriteria,
      summary: 'Auto-draft disabled (manual generation available anytime)',
    };
  }

  if (rules.requireLocated && !params.isLocated) {
    unmetCriteria.push('Event does not have a finalized epicenter location yet');
  } else if (params.isLocated) {
    matchedCriteria.push('Event has an adopted hypocenter location');
  }

  const meetsMag =
    params.magnitudeValue !== null && params.magnitudeValue >= rules.minMagnitude;
  const meetsPeis =
    rules.minPeisTrigger !== 'none' &&
    params.maxVerifiedPeis !== null &&
    peisRank(params.maxVerifiedPeis) >= peisRank(rules.minPeisTrigger);

  if (meetsMag) {
    matchedCriteria.push(
      `Magnitude ${params.magnitudeScale} ${params.magnitudeValue!.toFixed(1)} >= ${rules.minMagnitude.toFixed(1)}`
    );
  }
  if (meetsPeis) {
    matchedCriteria.push(
      `Verified PEIS ${params.maxVerifiedPeis} >= PEIS ${rules.minPeisTrigger}`
    );
  }

  if (!meetsMag && !meetsPeis) {
    const magDesc =
      params.magnitudeValue !== null
        ? `${params.magnitudeScale} ${params.magnitudeValue.toFixed(1)} < ${rules.minMagnitude.toFixed(1)}`
        : 'Magnitude not yet determined';
    const peisDesc =
      rules.minPeisTrigger !== 'none'
        ? ` and verified intensity below PEIS ${rules.minPeisTrigger}`
        : '';
    unmetCriteria.push(`${magDesc}${peisDesc}`);
  }

  if (params.isSolutionStale) {
    unmetCriteria.push(
      'Adopted location solution is stale relative to modified station picks — re-run PLOT and adopt before auto-drafting'
    );
  }

  const eligible =
    (!rules.requireLocated || params.isLocated) &&
    !params.isSolutionStale &&
    (meetsMag || meetsPeis);

  return {
    eligible,
    activeMagnitude: params.magnitudeValue,
    maxVerifiedPeis: params.maxVerifiedPeis,
    matchedCriteria,
    unmetCriteria,
    summary: eligible
      ? `Meets auto-draft criteria (${matchedCriteria.join('; ')})`
      : `Below auto-draft threshold (${unmetCriteria.join('; ')})`,
  };
}

function buildSectionOverview(p: PrimerExtractedParameters): PrimerSection {
  const reviewFlags: string[] = [];
  const magClause =
    p.magnitudeValue !== null && p.magnitudeScale
      ? `a Magnitude ${p.magnitudeScale} ${p.magnitudeValue.toFixed(1)} earthquake`
      : 'an earthquake (magnitude pending determination)';
  const originTypeClause = p.originType ? `${p.originType.toLowerCase()} in origin` : 'of unconfirmed origin classification';
  const locClause = p.primaryLocationLabel
    ? `located near ${p.primaryLocationLabel}`
    : 'with epicenter location currently pending final determination';
  const pstDate = formatIsoDateHuman(p.originDatePst);
  const pstTime = formatPstTimeShort(p.originTimePst);
  const utcDate = formatIsoDateHuman(p.originDateUtc);
  const utcTime = formatUtcTimeShort(p.originTimeUtc);
  const depthClause =
    p.depthKm !== null
      ? `at a focal depth of ${p.depthKm.toFixed(1)} km${p.depthFixed ? ' (depth fixed during inversion)' : ''}`
      : 'at an undetermined focal depth';

  if (p.magnitudeValue === null) reviewFlags.push('Magnitude value missing or zero');
  if (!p.isLocated) reviewFlags.push('Epicenter location pending');
  if (!p.originType) reviewFlags.push('Origin type (Tectonic/Volcanic) not specified');
  if (p.isSolutionStale) reviewFlags.push('PLOT solution is stale relative to modified phase picks');
  reviewFlags.push('Initial draft overview requires duty seismologist scientific review');

  const lines = [
    `On ${pstDate} at ${pstTime} (${utcDate}, ${utcTime}), the Philippine Institute of Volcanology and Seismology (PHIVOLCS) recorded ${magClause}, ${originTypeClause}, ${locClause}, ${depthClause}.`,
    '',
    `Event Reference: ${p.eventId} (Earthquake Bulletin No. ${p.bulletinNo} · Source File: ${p.filename})`,
  ];

  if (p.magnitudeValue === null || !p.isLocated || p.isSolutionStale) {
    lines.push(
      '',
      '[REQUIRES INFORMATION / SCIENTIFIC REVIEW: Verify finalized hypocenter, preferred magnitude scale, and latest Earthquake Information Bulletin parameters prior to public issuance.]'
    );
  }

  const content = lines.join('\n');
  const reviewStatus: PrimerSectionReviewStatus =
    p.magnitudeValue === null || !p.isLocated
      ? 'requires-info'
      : 'requires-scientific-review';

  return {
    id: 'overview',
    order: 1,
    title: '1. Earthquake Overview',
    content,
    reviewStatus,
    reviewFlags,
    isEdited: false,
    autoGeneratedBaseline: content,
  };
}

function buildSectionLocation(p: PrimerExtractedParameters): PrimerSection {
  const reviewFlags: string[] = [];
  const lines: string[] = [];

  if (!p.isLocated || p.lat === null || p.lon === null || p.depthKm === null) {
    reviewFlags.push('Epicenter latitude/longitude and depth are unlocated or pending');
    lines.push(
      '[REQUIRES INFORMATION: Hypocenter coordinates, focal depth, and nearest geographic reference localities have not been finalized for this event.]'
    );
    lines.push(`Station Picks Available: ${p.stationCount} (${p.activeStationCount} active)`);
  } else {
    lines.push(
      `Epicenter Coordinates: ${p.lat.toFixed(3)}°N, ${p.lon.toFixed(3)}°E`
    );
    lines.push(
      `Focal Depth: ${p.depthKm.toFixed(1)} km${
        p.depthFixed
          ? ` (fixed${p.depthFixReason ? ` — ${p.depthFixReason}` : ''})`
          : ' (free-depth solution)'
      }`
    );
    lines.push(
      `Nearest Locality Reference: ${p.primaryLocationLabel ?? '[REQUIRES INFORMATION: Nearest city/municipality reference unavailable]'}`
    );
    if (p.centralOfficeBearing) {
      lines.push(`Distance from Central Office: ${p.centralOfficeBearing}`);
    }
    const diagParts: string[] = [];
    if (p.rmsSec !== null) diagParts.push(`RMS: ${p.rmsSec.toFixed(2)} s`);
    if (p.errKm !== null) diagParts.push(`Horizontal Uncertainty: ±${p.errKm.toFixed(2)} km`);
    diagParts.push(`Stations Used/Total: ${p.activeStationCount}/${p.stationCount}`);
    if (p.locationModelName) diagParts.push(`Velocity Model: ${p.locationModelName}`);
    lines.push(`Solution Diagnostics: ${diagParts.join(' · ')}`);

    if (!p.primaryLocationLabel) {
      reviewFlags.push('Nearest city/municipality reference not populated');
    }
    if (p.isSolutionStale) {
      reviewFlags.push('Adopted solution is stale; re-run PLOT and adopt updated location');
      lines.push(
        '',
        '[REQUIRES SCIENTIFIC REVIEW: Station phase picks were modified after the last adopted location.]'
      );
    }
    if (p.errKm !== null && p.errKm > 10) {
      reviewFlags.push(`Elevated location uncertainty (±${p.errKm.toFixed(2)} km)`);
    }
  }

  const reviewStatus: PrimerSectionReviewStatus = !p.isLocated
    ? 'requires-info'
    : reviewFlags.length > 0
      ? 'requires-scientific-review'
      : 'ready-for-review';

  const content = lines.join('\n');
  return {
    id: 'location',
    order: 2,
    title: '2. Earthquake Location & Hypocenter Parameters',
    content,
    reviewStatus,
    reviewFlags,
    isEdited: false,
    autoGeneratedBaseline: content,
  };
}

